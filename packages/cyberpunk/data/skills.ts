/** Look up a skill definition by name (lowercase, underscored). */
export const getSkill = (name: string): ISkillDef | undefined =>
  SKILLS.find((s) => s.name === name.toLowerCase().replace(/[\s\-]/g, "_"));

/** All basic skills — must start at level 2 in chargen. */
export const BASIC_SKILLS = SKILLS.filter((s) => s.basic);

/** Display name for a skill key. */
export const skillDisplayName = (name: string): string =>
  name.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
